"""The eval harness. One command, reproducible, writes docs/12-eval-results.md.

    python -m eval.run_eval
    python -m eval.run_eval --limit 20 --split val

It enters the pipeline where a user does: no privileged access to reference data, no special
inference path (hard rule 4). It reports **per land-cover class**, because the pooled figure
demonstrably hides the result -- building correlation is positive while canopy correlation
is not, and pooling averages them into apparent noise.

What it will not do:

  * print an absolute RMSE for a relative prediction. Phase 1 has no calibration, so metric
    error is undefined and the field stays empty rather than being filled with a number that
    looks like accuracy.
  * report a landscape class we have no data for. Hilly and forested read NO DATA (D-02),
    never an estimate from the three flat cities we happen to have.
  * hand-edit its own output. This file overwrites docs/12-eval-results.md wholesale.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from depthwizard import backbone, config, dsm  # noqa: E402
from eval import metrics  # noqa: E402
from eval.scenes import Tile, discover  # noqa: E402


def _git_commit() -> str:
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True,
                             text=True, timeout=10, cwd=config.ROOT, check=False)
        return out.stdout.strip() or "unknown"
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def evaluate(tiles: list[Tile], size: str, stub: bool) -> dict:
    """Run the pipeline over every tile and score it, pooled and per class."""
    per_class: dict[str, list] = {}
    pooled: list = []
    rows: list[dict] = []

    for i, tile in enumerate(tiles, 1):
        print(f"  [{i}/{len(tiles)}] {tile.stem}", flush=True)
        rgb = tile.rgb()
        result = (backbone.estimate_stub(rgb) if stub
                  else backbone.estimate_relative_depth(rgb, size))
        pred, ref, cls = result.relative, tile.agl(), tile.cls()

        # Phase 1 output is relative, so metric=False and the absolute fields stay None.
        overall = metrics.score(pred, ref, metric=False)
        if overall is None:
            print("        skipped -- not enough valid data")
            continue
        pooled.append(overall)
        row = {"tile": tile.stem, "city": tile.city, "split": tile.split,
               "all": overall.as_dict(), "classes": {}}

        for index, name in config.GAMUS_CLASS_NAMES.items():
            if index == config.GAMUS_BACKGROUND_CLASS:
                continue
            mask = cls == index
            if mask.sum() < 500:
                continue
            scored = metrics.score(pred, ref, metric=False, mask=mask)
            if scored is None:
                continue
            per_class.setdefault(name, []).append(scored)
            row["classes"][name] = {"r": scored.pearson_r,
                                    "share": float(mask.mean())}
        rows.append(row)

    return {
        "rows": rows,
        "pooled": metrics.aggregate(pooled),
        "per_class": {k: metrics.aggregate(v) for k, v in per_class.items()},
    }


def render(results: dict, tiles: list[Tile], size: str, stub: bool) -> str:
    pooled = results["pooled"]
    cities = sorted({t.city for t in tiles})
    lines = [
        "# Eval results",
        "",
        "> **Generated by `python -m eval.run_eval`. Never hand-edited** (hard rule 1).",
        f"> Run {datetime.now(timezone.utc).isoformat(timespec='seconds')}, "
        f"commit `{_git_commit()}`.",
        "",
        "---",
        "",
        "## What was run",
        "",
        "| | |",
        "|---|---|",
        f"| Backbone | `{backbone.CHECKPOINTS.get(size, 'stub')}`, frozen, zero-shot |",
        "| Calibration | **none** — Phase 2 not built |",
        f"| Tiles | {len(results['rows'])} |",
        f"| Cities | {', '.join(cities) or 'none'} |",
        f"| Reference | GAMUS `_AGL`, LiDAR-derived, metres above ground |",
        "",
    ]

    if stub:
        lines += ["> **STUB RUN — the backbone did not execute.** These numbers describe a "
                  "deterministic placeholder and are not a result.", ""]

    lines += [
        "## Absolute accuracy",
        "",
        "**Not measured.** The pipeline outputs relative heights until scale calibration "
        "exists (D-05), so RMSE, MAE and bias in metres are undefined. Reporting them would "
        "mean inventing a scale. Scale-free agreement is below.",
        "",
        "## Scale-free agreement with LiDAR",
        "",
    ]

    if not pooled:
        lines += ["No tiles scored.", ""]
    else:
        lines += [
            "| Scope | r | SI-RMSE (m) | SI-MAE (m) | tiles | pixels |",
            "|---|---|---|---|---|---|",
            f"| **All pixels** | **{pooled['pearson_r']:+.4f}** | {pooled['si_rmse']:.2f} | "
            f"{pooled['si_mae']:.2f} | {pooled['tiles']} | {pooled['pixels']:,} |",
        ]
        for name, agg in sorted(results["per_class"].items(),
                                key=lambda kv: -(kv[1] or {}).get("pearson_r", -9)):
            if not agg:
                continue
            lines.append(
                f"| {name} | {agg['pearson_r']:+.4f} | {agg['si_rmse']:.2f} | "
                f"{agg['si_mae']:.2f} | {agg['tiles']} | {agg['pixels']:,} |")
        lines += ["", "Pixel-weighted across tiles. Per-class rows use the legend resolved in "
                  f"U-01 (evidence base: {config.GAMUS_CLASS_LEGEND_TILES} tiles).", ""]

    lines += [
        "## Stratification the brief requires",
        "",
        "> *\"performance stability across urban, sparse, hilly, and forested landscapes\"*",
        "",
        "| Landscape | Status |",
        "|---|---|",
    ]
    for landscape in config.LANDSCAPE_CLASSES:
        if landscape in config.LANDSCAPE_WITHOUT_DATA:
            lines.append(f"| {landscape} | **NO DATA** — see D-02 in `11-deferred.md` |")
        else:
            lines.append(f"| {landscape} | not yet labelled per tile; see per-class table above |")
    lines += [
        "",
        "Landscape labelling is not built, and for hilly and forested **no data exists at "
        "all** — the GAMUS mirror is three flat US cities. Those rows will not be filled in "
        "with an estimate.",
        "",
        "## Per tile",
        "",
        "| Tile | city | r (all) | r (building) | r (tree) |",
        "|---|---|---|---|---|",
    ]
    for row in results["rows"]:
        b = row["classes"].get("building", {}).get("r")
        t = row["classes"].get("tree", {}).get("r")
        lines.append(
            f"| {row['tile']} | {row['city']} | {row['all']['pearson_r']:+.4f} | "
            f"{b:+.4f} |" .replace("None", "—") if b is not None else
            f"| {row['tile']} | {row['city']} | {row['all']['pearson_r']:+.4f} | — |")
        lines[-1] += f" {t:+.4f} |" if t is not None else " — |"

    unsourced = config.placeholders()
    if unsourced:
        lines += ["", "## Values still unsourced", "",
                  "Any number above that rests on one of these carries its uncertainty:", ""]
        lines += [f"- `{p.key}` ({p.doc_ref}) — blocks {p.blocks}" for p in unsourced]

    lines += ["", "---", "",
              f"**Sample size: {len(results['rows'])} tiles"
              f"{' from ' + ', '.join(cities) if cities else ''}.** "
              "Quote it with every figure above."]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--split", default="val", choices=("train", "val", "test"))
    parser.add_argument("--limit", type=int, help="cap the number of tiles")
    parser.add_argument("--size", choices=sorted(backbone.CHECKPOINTS),
                        default=backbone.DEFAULT_SIZE)
    parser.add_argument("--stub", action="store_true", help="skip the model; NOT a result")
    parser.add_argument("--out", default=str(config.EVAL_RESULTS))
    args = parser.parse_args()

    tiles = discover(config.GAMUS_ROOT, args.split, args.limit)
    if not tiles:
        print(f"No complete tile triplets in split '{args.split}' under {config.GAMUS_ROOT}.")
        print("Fetch some:  python -m tools.fetch_datasets --sample 20 --split val")
        return 1

    print(f"evaluating {len(tiles)} tiles from '{args.split}'")
    results = evaluate(tiles, args.size, args.stub)
    if not results["rows"]:
        print("nothing scored")
        return 1

    Path(args.out).write_text(render(results, tiles, args.size, args.stub), encoding="utf8")
    print(f"\nwrote {args.out}")

    pooled = results["pooled"]
    print(f"\n  all pixels     r = {pooled['pearson_r']:+.4f}")
    for name, agg in sorted(results["per_class"].items(),
                            key=lambda kv: -(kv[1] or {}).get("pearson_r", -9)):
        if agg:
            print(f"  {name:14s} r = {agg['pearson_r']:+.4f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
